import com.example.sonora.domain.model.RadioLanguage
import java.util.Locale

/**
 * The selected radio language also controls the entire application interface.
 * All six supported languages have their own complete UI dictionary.
 */
fun uiText(language: RadioLanguage?, key: String, vararg args: Any): String {
    val translations = when (language?.code) {
        "ru" -> russian
        "zh" -> chinese
        "tr" -> turkish
        "it" -> italian
        "be" -> belarusian
        else -> english
    }
    val template = translations[key] ?: english[key] ?: key
    return if (args.isEmpty()) template else String.format(Locale.ROOT, template, *args)
}

